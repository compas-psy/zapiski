-- SEC-001 §10 — установить ФАКТ: есть ли в проде объекты прошлых версий.
--
-- ── Зачем этот файл существует ──────────────────────────────────────────────
--
-- Вопрос «строить ли миграцию» решается фактом, а не предположением. Из
-- контейнера разработки прод-база недоступна, поэтому здесь лежат ровно те
-- запросы, которые отвечают на вопрос, и объяснение, почему они на него
-- отвечают. Выполнять от роли, имеющей SELECT на схеме приложения:
--
--   psql "$DATABASE_URL" -f docs/dev/security/SEC-001-legacy-check.sql
--
-- ── Почему по этим признакам вообще можно судить ────────────────────────────
--
-- До перехода Облако адресовало объект его НАСТОЯЩИМ путём («Личное/
-- Дневник.md») и клало содержимое как есть. После перехода адрес — токен
-- HMAC-SHA256(K_manifest, путь), обрезанный до 128 бит и записанный hex, то
-- есть РОВНО 32 шестнадцатеричных знака без точки и без косой черты. Путь
-- заметки такой формы иметь не может: у него есть расширение (.md, .md.enc)
-- либо разделитель каталогов. Значит форма адреса — надёжный различитель,
-- и ровно им пользуется `ZapiskiCloudBackend.migrateLegacy()`.
--
-- Содержимое блобов и версий лежит не в Postgres, а в томе на диске
-- (`storage_key`), поэтому по содержимому их отсюда не проверить — и не
-- нужно: адрес отвечает на вопрос однозначно. CRDT-апдейты лежат прямо
-- здесь (`crdt_updates.ciphertext`), и у них проверяется сам конверт:
-- первый байт версии формата = 1 и длина больше 12 байт nonce + 16 байт
-- тега GCM.
--
-- ── Как читать ответ ────────────────────────────────────────────────────────
--
--   везде 0 → мигрировать нечего, фреймворк миграции не нужен;
--   есть ненулевые → у этих аккаунтов объекты прошлых версий есть, и они
--   переедут сами при первом же подключении облака на клиенте новой версии
--   (`migrateLegacy`: перечитать → положить запечатанным по новому адресу →
--   убрать открытую копию). Ничего дополнительно запускать не нужно —
--   запросы ниже покажут убывание к нулю.

\echo '── 1. Аккаунты, перешедшие на шифрование ───────────────────────────────'
SELECT count(*) AS enrolled_accounts FROM sync_keys;

\echo '── 2. Блобы по форме адреса ────────────────────────────────────────────'
SELECT
  count(*) FILTER (WHERE path ~ '^[0-9a-f]{32}$')  AS token_addressed,
  count(*) FILTER (WHERE path = '.zapiski-manifest') AS manifests,
  count(*) FILTER (
    WHERE path !~ '^[0-9a-f]{32}$' AND path <> '.zapiski-manifest'
  ) AS legacy_plaintext_paths
FROM blobs
WHERE deleted_at IS NULL;

\echo '── 3. Те же блобы, но только у зашифрованных аккаунтов ─────────────────'
-- Это и есть настоящая цель миграции: у аккаунта ключ уже есть, а объект
-- лежит по старому адресу. У аккаунта без ключа «старый адрес» — норма.
SELECT count(*) AS legacy_on_enrolled_accounts
FROM blobs b
JOIN sync_keys k ON k.user_id = b.user_id
WHERE b.deleted_at IS NULL
  AND b.path !~ '^[0-9a-f]{32}$'
  AND b.path <> '.zapiski-manifest';

\echo '── 4. Версии заметок ───────────────────────────────────────────────────'
SELECT count(*) AS legacy_versions
FROM versions v
JOIN sync_keys k ON k.user_id = v.user_id
WHERE v.path IS NOT NULL AND v.path !~ '^[0-9a-f]{32}$';

\echo '── 5. CRDT-апдейты без конверта ────────────────────────────────────────'
-- Конверт: [версия(1)=1][nonce(12)][шифротекст+тег(16)] — значит минимум
-- 30 байт, и первый байт равен 1.
SELECT count(*) AS legacy_crdt_updates
FROM crdt_updates c
JOIN sync_keys k ON k.user_id = c.user_id
WHERE octet_length(c.ciphertext) <= 29
   OR get_byte(c.ciphertext, 0) <> 1;

\echo '── 6. По аккаунтам: кому именно ещё предстоит переезд ──────────────────'
SELECT b.user_id, count(*) AS legacy_objects
FROM blobs b
JOIN sync_keys k ON k.user_id = b.user_id
WHERE b.deleted_at IS NULL
  AND b.path !~ '^[0-9a-f]{32}$'
  AND b.path <> '.zapiski-manifest'
GROUP BY b.user_id
ORDER BY legacy_objects DESC
LIMIT 50;
