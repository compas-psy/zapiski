/**
 * Заголовок отдельным полем (ITERATION-1 §1).
 *
 * Дефект, ради которого написан файл, виден на скриншоте: заметка называлась
 * «###». Заголовком считалась первая непустая строка, чем бы она ни была, — и
 * в список попадал случайный обрывок разметки.
 *
 * Главное свойство здесь — обратимость. Заголовок живёт в файле первой строкой
 * `# Название`, а не в отдельном поле базы: удалив приложение, человек обязан
 * увидеть в чужом редакторе ровно то же, что видел у нас. Значит, разбор и
 * сборка должны возвращать исходный текст байт в байт.
 */
import { describe, expect, it } from 'vitest';

import { extractTitle, parseNote } from '../src/markdown/parse.js';
import { joinTitle, splitTitle } from '../src/markdown/title.js';

describe('разбор заголовка', () => {
  it('первая строка `# Название` — заголовок, тело без неё', () => {
    const { title, body } = splitTitle('# Планы на неделю\n\nкупить билеты\nзабрать посылку\n');
    expect(title).toBe('Планы на неделю');
    expect(body).toBe('купить билеты\nзабрать посылку\n');
  });

  it('файл без H1: заголовок пуст, текст остаётся телом целиком', () => {
    /* Чужой vault. Ничего не переносим и не переписываем (§1). */
    const text = 'купить билеты\nзабрать посылку\n';
    expect(splitTitle(text)).toEqual({ title: '', body: text });
  });

  it('`###` больше не становится названием', () => {
    /* Ровно случай со скриншота. */
    expect(splitTitle('###\n').title).toBe('');
    expect(extractTitle('###\n')).toBe('');
  });

  it('H2 и глубже — часть тела, а не название', () => {
    const text = '## Раздел\n\nтекст\n';
    expect(splitTitle(text)).toEqual({ title: '', body: text });
  });

  it('текст до первого H1 оставляет заголовок пустым', () => {
    const text = 'преамбула\n\n# Название\n\nтекст\n';
    expect(splitTitle(text)).toEqual({ title: '', body: text });
  });

  it('пустые строки перед заголовком не мешают', () => {
    expect(splitTitle('\n\n# Название\n\nтекст\n').title).toBe('Название');
  });

  it('разметка в заголовке остаётся текстом', () => {
    /* §1: «Разметка внутри поля не работает: ** останется звёздочками». */
    expect(splitTitle('# **Важное**\n\nтекст\n').title).toBe('**Важное**');
  });

  it('frontmatter остаётся в теле и не мешает найти заголовок', () => {
    const text = '---\nid: abc\n---\n# Название\n\nтекст\n';
    const { title, body } = splitTitle(text);
    expect(title).toBe('Название');
    expect(body).toContain('id: abc');
    expect(body).not.toContain('# Название');
  });
});

describe('сборка файла обратно', () => {
  it('разбор и сборка возвращают исходный текст', () => {
    for (const text of [
      '# Название\n\nтекст\n',
      '# Название\n',
      'текст без заголовка\n',
      '## Раздел\n\nтекст\n',
      '---\nid: abc\n---\n# Название\n\nтекст\n',
      '',
    ]) {
      const { title, body } = splitTitle(text);
      expect(joinTitle(title, body), JSON.stringify(text)).toBe(text);
    }
  });

  it('пустой заголовок не пишет пустой H1', () => {
    /* Иначе файл без названия получил бы строку `# ` и открывался бы чужим
       редактором иначе, чем открывался. */
    expect(joinTitle('', 'текст\n')).toBe('текст\n');
    expect(joinTitle('   ', 'текст\n')).toBe('текст\n');
  });

  it('заголовок, набранный в пустой заметке, создаёт строку сверху', () => {
    expect(joinTitle('Название', '')).toBe('# Название\n');
    expect(joinTitle('Название', 'текст\n')).toBe('# Название\n\nтекст\n');
  });

  it('смена заголовка не трогает тело', () => {
    const { body } = splitTitle('# Старое\n\nтекст\nвторая строка\n');
    expect(joinTitle('Новое', body)).toBe('# Новое\n\nтекст\nвторая строка\n');
  });
});

describe('сниппет в строке списка', () => {
  it('не дублирует заголовок', () => {
    const { title, snippet } = parseNote('# Планы\n\nкупить билеты\n');
    expect(title).toBe('Планы');
    expect(snippet).toBe('купить билеты');
  });

  it('у заметки без заголовка начало текста не съедается', () => {
    /* Прежде отрезалась первая непустая строка — то есть само начало текста. */
    const { title, snippet } = parseNote('купить билеты\nзабрать посылку\n');
    expect(title).toBe('');
    expect(snippet).toBe('купить билеты забрать посылку');
  });
});
