/**
 * Заметка в мессенджер: разбирается ли то, что мы отправляем.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * Заказчик прислал два снимка рядом: заметка в ЗАПИСКАХ и она же, отправленная
 * в Telegram. «Сейчас это там выглядит ужасно, но оба мессенджера поддерживают
 * MarkDown». В Telegram приехало `# Психологов развелось!`, `**Слишком много
 * выбора.**` звёздочками, `> цитата` палкой, `![](Images/2026-08-15_4d619f.png)`
 * и `[ilyamartynov.ru](https://ilyamartynov.ru)` скобками.
 *
 * Мы отправляли markdown КАК ЕСТЬ и писали в тесте, что «разбирать разметку —
 * работа принимающей стороны». Это оказалось неправдой, и проверить её было
 * нечем: тест сверял отправленное с исходником, а не с тем, что получатель
 * умеет прочитать.
 *
 * ── Чем проверено ───────────────────────────────────────────────────────────
 *
 * Исходниками клиента Telegram для Android:
 *
 *   `LaunchActivity` приводит пришедший `EXTRA_TEXT` к строке, то есть любое
 *   оформление на уровне Android теряется; далее текст идёт через
 *   `MediaDataController.getEntities`, а он знает ровно шесть видов разметки,
 *   заданных регулярками:
 *       BOLD    \*\*(.+?)\*\*      ITALIC  __(.+?)__
 *       SPOILER \|\|(.+?)\|\|      STRIKE  ~~(.+?)~~
 *   плюс `код` и ```блок```. Ссылки собираются только из `URLSpan`, поэтому
 *   `[имя](адрес)` текстом ссылкой не станет никогда.
 *
 * И документацией MAX: разметка там — параметр Bot API (`format: "markdown"` в
 * `NewMessageBody`), то есть привилегия БОТА, а не разбор текста, который
 * человек прислал через «Поделиться».
 *
 * Отсюда два обещания, и оба проверяются ниже:
 *
 *   1. в исходящем тексте не остаётся НИ ОДНОГО маркера, которого получатель
 *      не понимает (`# `, `> `, `- `, `![](…)`, `[имя](адрес)`, `<u>`, `==`);
 *   2. структура заметки — заголовки, списки, цитаты, таблицы — держится на
 *      ОБЫЧНЫХ СИМВОЛАХ (`•`, `☐`, `│`, `———`), а не на разметке. Поэтому
 *      текст читается даже там, где не разберут вообще ничего: на снимке
 *      заказчика Telegram показал звёздочками даже то, что по исходникам
 *      обязан был разобрать.
 */
import { describe, expect, it } from 'vitest';

import { toMessengerText } from '../src/markdown/messenger.js';

/** Заметка со снимка заказчика — с тем же набором разметки. */
const NOTE = `---
tags: [пост]
---

# Психологов развелось!

#пост

![](Images/2026-08-15_4d619f.png)

> "Плох тот пациент, который не хочет стать психологом… для самого себя"
> — Марк Сандомирский (на фото)

"Психологов развелось" — слышу это всё чаще. И действительно: учиться на
психолога идут толпами.

**Слишком много выбора.** Раньше жизнь была более-менее расчерчена вперёд:
школа, институт, работа.

- первый довод
- второй довод

1. Плох тот пациент
2. Хорош тот психолог

- [ ] не сделано
- [x] сделано

*курсивом* и ~~зачёркнутым~~ и <u>подчёркнутым</u> и ==подсветкой==

\`инлайн-код\` рядом

[ilyamartynov.ru](https://ilyamartynov.ru)

[Мой сайт](https://ilyamartynov.ru)

---
`;

describe('в мессенджер уходит то, что он умеет прочитать', () => {
  const out = toMessengerText(NOTE);

  it('заголовок становится жирной строкой: заголовков у мессенджера нет', () => {
    expect(out).toContain('**Психологов развелось!**');
    expect(out).not.toContain('# Психологов');
  });

  it('курсив уезжает двойным подчёркиванием — одиночную звёздочку Telegram не знает', () => {
    expect(out).toContain('__курсивом__');
    expect(out).not.toContain('*курсивом*');
  });

  it('жирный и зачёркнутый остаются как есть — их синтаксис совпадает', () => {
    expect(out).toContain('**Слишком много выбора.**');
    expect(out).toContain('~~зачёркнутым~~');
  });

  it('подчёркивание и подсветка теряют разметку, но не текст', () => {
    expect(out).toContain('подчёркнутым');
    expect(out).toContain('подсветкой');
    expect(out).not.toContain('<u>');
    expect(out).not.toContain('==');
  });

  it('картинка не превращается в мусор: файла у получателя нет', () => {
    expect(out).not.toContain('![');
    expect(out).not.toContain('Images/');
  });

  /**
   * Ширина картинки — наша служебная запись, а не подпись.
   *
   * На снимке заказчика из `![|258](Images/…)` в Telegram уехала отдельная
   * строка «|258». Подпись сохраняем, ширину снимаем.
   */
  it('ширина картинки не уезжает отдельной строкой', () => {
    expect(toMessengerText('![|258](Images/a.png)')).toBe('');
    expect(toMessengerText('![Марк на фото|258](Images/a.png)')).toBe('Марк на фото');
  });

  it('ссылка приезжает адресом, который мессенджер подсветит сам', () => {
    /* Подпись совпала с адресом — остаётся один адрес. */
    expect(out).toContain('https://ilyamartynov.ru');
    /* Подпись своя — остаётся и она, и адрес. */
    expect(out).toContain('Мой сайт — https://ilyamartynov.ru');
    expect(out).not.toContain('](');
  });

  it('список читается списком без всякой разметки', () => {
    expect(out).toContain('• первый довод');
    expect(out).toContain('1. Плох тот пациент');
    expect(out).toContain('☐ не сделано');
    expect(out).toContain('☑ сделано');
    expect(out).not.toMatch(/^- /m);
  });

  it('цитата набирается чертой и курсивом — блока цитаты у мессенджера нет', () => {
    expect(out).toMatch(/__[^\n]*Плох тот пациент[^\n]*__/);
    expect(out).toMatch(/__— Марк Сандомирский \(на фото\)__/);
    expect(out).not.toMatch(/^> /m);
    /* Черта — обычный символ: она видна и там, где курсив не разобрали. */
    expect(out).toMatch(/^│ .*Плох тот пациент/m);
    expect(out).toMatch(/^│ .*Марк Сандомирский/m);
  });

  /**
   * Пара маркеров НИКОГДА не переходит на новую строку.
   *
   * Разметка Telegram задана обычными java-регулярками (`__(.+?)__`), а точка
   * в java по умолчанию не совпадает с переводом строки. Многострочная пара не
   * разберётся, и получатель увидит сырые подчёркивания — ровно то, что
   * заказчик назвал ужасным. Проверяется по чётности маркеров в каждой строке.
   */
  it('ни одна пара маркеров не разорвана переводом строки', () => {
    const broken = out
      .split('\n')
      .filter((line) => !line.startsWith('```'))
      .filter((line) => {
        const count = (marker: string): number => line.split(marker).length - 1;
        return count('**') % 2 !== 0 || count('__') % 2 !== 0 || count('~~') % 2 !== 0;
      });
    expect(broken, 'многострочная пара маркеров у получателя не разберётся').toEqual([]);
  });

  it('служебные поля заметки получателю не уезжают', () => {
    expect(out).not.toContain('tags:');
    expect(out).not.toContain('---\n');
  });

  it('тег остаётся тегом: мессенджеры делают из него ссылку сами', () => {
    expect(out).toContain('#пост');
  });

  it('инлайн-код остаётся кодом: его синтаксис Telegram знает', () => {
    expect(out).toContain('`инлайн-код`');
  });

  /**
   * Главная проверка файла.
   *
   * Не «текст похож на нужный», а «в нём нет ничего, что получатель покажет
   * сырым». Список запрещённого — прямое следствие разбора исходников
   * Telegram: всё, чего нет в его шести регулярках.
   */
  it('ни одного маркера, которого получатель не понимает', () => {
    const lines = out.split('\n');
    const leftovers = lines.filter(
      (line) =>
        /^#{1,6}\s/.test(line) || // заголовки
        /^>\s/.test(line) || // цитаты
        /^[-*+]\s/.test(line) || // маркеры списков
        /!\[/.test(line) || // картинки
        /\]\(/.test(line) || // ссылки
        /<\/?[a-z]/i.test(line) || // html-теги
        /==/.test(line), // подсветка
    );
    expect(leftovers, 'в мессенджер уедет сырая разметка').toEqual([]);
  });
});

describe('простой текст: получатель не умеет ничего', () => {
  const out = toMessengerText(NOTE, { flavour: 'plain' });

  it('маркеров не остаётся вовсе — только текст', () => {
    expect(out).not.toContain('**');
    expect(out).not.toContain('__');
    expect(out).not.toContain('~~');
    expect(out).not.toContain('```');
    expect(out).toContain('Психологов развелось!');
    expect(out).toContain('Слишком много выбора.');
  });

  it('списки и тут читаются списками', () => {
    expect(out).toContain('• первый довод');
    expect(out).toContain('☑ сделано');
  });

  /**
   * Худший случай — и он же самый вероятный.
   *
   * Здесь получатель не разбирает ничего вовсе. Значит структура обязана
   * держаться на символах: черта у цитаты, точка у пункта, квадрат у задачи,
   * черта-разделитель. Если эта проверка упадёт, человек получит сплошную
   * простыню — то, ради чего всё и затевалось.
   */
  it('структура держится символами, а не разметкой', () => {
    expect(out).toMatch(/^│ .*Плох тот пациент/m);
    expect(out).toContain('———');
    expect(out).toContain('1. Плох тот пациент');
    /* И ни одного знака, который человеку читать не нужно. */
    for (const marker of ['**', '__', '~~', '`', '#Психологов', '](', '![', '<u>', '==']) {
      expect(out, `«${marker}» уедет человеку в глаза`).not.toContain(marker);
    }
  });
});

describe('края, на которых легко испортить чужой текст', () => {
  it('пустая заметка не превращается в набор маркеров', () => {
    expect(toMessengerText('')).toBe('');
    expect(toMessengerText('# \n\n')).toBe('');
  });

  it('таблица уезжает моноширинным блоком — иначе столбцы расползаются', () => {
    const out = toMessengerText('| Кто | Что |\n| --- | --- |\n| Марк | цитата |\n');
    expect(out.startsWith('```')).toBe(true);
    expect(out).toContain('Кто');
    expect(out).toContain('Марк');
    expect(out).not.toContain('|');
  });

  it('код-блок остаётся кодом вместе с языком', () => {
    const out = toMessengerText('```ts\nconst a = 1;\n```\n');
    expect(out).toContain('```ts');
    expect(out).toContain('const a = 1;');
  });

  it('разделитель читается чертой, а не тремя дефисами', () => {
    expect(toMessengerText('текст\n\n---\n\nещё\n')).toContain('———');
  });

  it('вики-ссылка отдаётся подписью: у получателя нашего хранилища нет', () => {
    expect(toMessengerText('см. [[Практика|мои заметки]]')).toContain('мои заметки');
    expect(toMessengerText('см. [[Практика|мои заметки]]')).not.toContain('[[');
  });
});
