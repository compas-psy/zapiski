/**
 * Когда можно спросить «рассказать, что пошло не так?» — и когда нельзя.
 *
 * ── Почему это правило, а не «покажем после сбоя» ───────────────────────────
 *
 * Приложение для психолога. Сбой случается не в вакууме: человек в этот момент
 * между сессиями или после трудной встречи. Полоса, выскакивающая на каждую
 * неудачу, за неделю превращается в фон, который перестают читать, — а вместе с
 * ней перестают читать и всё остальное, что мы говорим.
 *
 * Поэтому два предела, и оба здесь:
 *
 *   · показали — сутки не показываем ничего, каким бы ни был следующий повод;
 *   · отказались — неделя. Отказ это ответ, а не пауза, и переспрашивать
 *     назавтра значит не услышать его.
 *
 * Отказ сильнее показа: он и живёт дольше, и учитывается первым.
 *
 * Правило чистое (время приходит аргументом) ровно затем, чтобы его можно было
 * проверить, а не «понаблюдать неделю на устройстве».
 */
import { describe, expect, it } from 'vitest';

import { DISMISS_QUIET_MS, PROMPT_QUIET_MS, shouldOfferFeedback } from '../src/index.js';

const DAY = 24 * 60 * 60 * 1000;
const NOW = Date.UTC(2026, 7, 17, 9, 0, 0);

describe('приглашение рассказать о проблеме', () => {
  it('первый раз показывается', () => {
    expect(shouldOfferFeedback({ now: NOW })).toBe(true);
  });

  it('в течение суток после показа — молчим', () => {
    expect(shouldOfferFeedback({ now: NOW, promptedAt: NOW - DAY / 2 })).toBe(false);
  });

  it('через сутки после показа — можно снова', () => {
    expect(shouldOfferFeedback({ now: NOW, promptedAt: NOW - PROMPT_QUIET_MS - 1 })).toBe(true);
  });

  it('после отказа молчим неделю, а не сутки', () => {
    /* Тот же момент, что и в проверке выше: разница только в том, ЧЕМ он был.
       Если бы отказ считался за показ, здесь было бы `true`, и человек, сказавший
       «нет», получил бы то же приглашение назавтра. */
    expect(shouldOfferFeedback({ now: NOW, dismissedAt: NOW - PROMPT_QUIET_MS - 1 })).toBe(false);
    expect(shouldOfferFeedback({ now: NOW, dismissedAt: NOW - DISMISS_QUIET_MS - 1 })).toBe(true);
  });

  it('неделя молчания считается от отказа, даже если после него показывали', () => {
    /* Порядок важен: сначала отказ, потом чей-то ошибочный показ. Правило
       обязано опираться на отказ, а не на последнее событие. */
    expect(
      shouldOfferFeedback({
        now: NOW,
        dismissedAt: NOW - 2 * DAY,
        promptedAt: NOW - 2 * DAY - 1,
      }),
      'отказ перебит показом',
    ).toBe(false);
  });

  it('часы, переведённые назад, не открывают дверь навсегда', () => {
    /*
     * Метка из будущего — не выдумка: пользователь переводит часы, часовой пояс
     * меняется в самолёте, устройство синхронизирует время после загрузки.
     * Наивное `now - promptedAt > сутки` при метке из будущего даёт
     * отрицательную разницу — то есть «молчим», и приглашение исчезало бы до
     * тех пор, пока реальное время не догонит метку. Неделя в самолёте —
     * неделя тишины.
     *
     * Правильное поведение — считать такую метку негодной и не молчать по ней.
     */
    expect(shouldOfferFeedback({ now: NOW, promptedAt: NOW + 30 * DAY })).toBe(true);
    expect(shouldOfferFeedback({ now: NOW, dismissedAt: NOW + 30 * DAY })).toBe(true);
  });

  it('мусор вместо метки не считается за отказ', () => {
    /* Настройки — обычный JSON на диске, и в них может оказаться что угодно:
       чужая запись, обрывок, `null` от прошлой версии. Такая метка не должна
       ни молчать вечно, ни ронять экран. */
    for (const junk of [Number.NaN, 0, -1, Number.POSITIVE_INFINITY]) {
      expect(shouldOfferFeedback({ now: NOW, dismissedAt: junk }), `метка ${junk}`).toBe(true);
    }
  });
});
