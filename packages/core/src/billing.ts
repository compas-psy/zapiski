/**
 * Берём ли мы деньги.
 *
 * ── Решение ─────────────────────────────────────────────────────────────────
 *
 * На MVP — нет. Всё, что продукт умеет, доступно каждому, кто вошёл: облако,
 * публикация, история версий. Оплату добавим потом, и тогда этот выключатель
 * встанет в `true` вместе с `BILLING_ENABLED=1` на сервере.
 *
 * ── Почему выключатель, а не удаление экранов ───────────────────────────────
 *
 * Экраны тарифов, тексты, цены и весь код подписки остаются на месте —
 * заказчик просил именно спрятать, а не уничтожить. Удалить и потом написать
 * заново — это выбросить проверенное: paywall без таймеров и с видимым
 * крестиком, честная таблица «бесплатно / плюс», отмена в один тап. Всё это
 * стоило работы и по-прежнему верно.
 *
 * ── Почему их два, здесь и на сервере ───────────────────────────────────────
 *
 * Разделение обязанностей, а не дублирование. Сервер решает, МОЖНО ли писать
 * в облако: там деньги, там и запрет. Этот флаг решает, ГОВОРИМ ли мы человеку
 * про тарифы. Спрятать paywall в интерфейсе, не сняв запрет на сервере,
 * означало бы «кнопок нет, а синхронизация всё равно отказывает» — ровно то,
 * что человек и увидел: «Подписка закончилась» сразу после первого входа.
 *
 * Оба по умолчанию выключены, и включать их надо вместе.
 */
export const BILLING_ENABLED = false;
