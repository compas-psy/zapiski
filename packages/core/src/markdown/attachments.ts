/**
 * Какие файлы заметки уходят вместе с ней.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 *
 * Заказчик: «чтобы при шеринге через стандартный инструментарий Android в
 * Telegram или Max форматирование там выглядело точь-в-точь, как в ЗАПИСКАХ».
 * Текст мы уже переводим (`messenger.ts`), но на снимке заказчика в заметке
 * есть ФОТОГРАФИЯ, а в мессенджер уезжала только строка `![|258](Images/…)` —
 * то есть картинка терялась целиком.
 *
 * Здесь собирается список того, что нужно приложить к тексту.
 *
 * ── Что сюда НЕ попадает и почему ───────────────────────────────────────────
 *
 *  · внешние адреса (`https://…`, `data:`) — это не наши файлы, они и так
 *    доступны получателю по ссылке, а тянуть их из сети ради отправки значило
 *    бы нарушить правило «работает в самолёте»;
 *  · не-картинки (pdf, аудио, архивы) — заметка про них рассказывает текстом,
 *    а отправка чужому человеку файла, которого он не просил, — это уже не
 *    «поделиться заметкой». Отдельным решением это можно расширить, но молча
 *    — нельзя;
 *  · повторы: одна и та же картинка, вставленная дважды, уезжает один раз.
 *
 * Порядок сохраняется — он же порядок в заметке.
 */
import { extractLinks, isImageUrl } from './parse.js';

/** Сколько картинок отправляем максимум. */
export const SHARE_IMAGE_LIMIT = 10;

/** Внешний адрес или встроенные данные: наш файл так не выглядит. */
function isExternal(url: string): boolean {
  return /^(?:[a-z][a-z0-9+.-]*:)?\/\//i.test(url) || url.startsWith('data:');
}

/**
 * Пути картинок заметки в хранилище — в порядке появления, без повторов.
 *
 * Ширина (`![подпись|258](…)`) остаётся в подписи, а не в адресе, поэтому
 * снимать её здесь не нужно: разбор ссылок отдаёт адрес отдельно.
 */
export function noteImagePaths(markdown: string, limit = SHARE_IMAGE_LIMIT): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const link of extractLinks(markdown)) {
    if (!link.image) continue;
    /* Якорь и параметры к файлу на диске отношения не имеют. */
    const path = (link.url.split('#')[0]?.split('?')[0] ?? '').trim();
    if (path === '' || isExternal(path)) continue;
    if (!isImageUrl(path)) continue;
    if (seen.has(path)) continue;
    seen.add(path);
    out.push(path);
    if (out.length >= limit) break;
  }
  return out;
}
