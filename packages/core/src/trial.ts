/**
 * Пробный период облака — одно правило на клиент и сервер.
 *
 * ── Решение заказчика ───────────────────────────────────────────────────────
 *
 * «Так как мы запустим ЗАПИСКИ сначала в MVP, то нужно при подключении облака
 * сделать дисклеймер, что в рамках тестовой версии приложения даётся триал
 * 30 дней без оплаты. Такой режим должен действовать для подключивших облако
 * до 01.09.2026. Далее триал сокращается до 14 дней».
 *
 * ── Почему правило живёт в ядре, а не в двух местах ─────────────────────────
 *
 * Число дней говорят ДВЕ стороны: интерфейс — словами при подключении облака,
 * сервер — датой окончания в подписке. Разъедься они на день, и человек увидит
 * обещание «30 дней», а доступ кончится раньше; доверие после такого не
 * возвращают. Поэтому правило — одна чистая функция, а обе стороны её зовут.
 *
 * Граница считается по МОМЕНТУ ПОДКЛЮЧЕНИЯ, а не по «сегодня»: у того, кто
 * подключился 31 августа, тридцать дней не превращаются в четырнадцать первого
 * сентября. Обещание, данное при подключении, остаётся в силе.
 */

/** Ранние 30 дней — тем, кто подключил облако СТРОГО до этого момента. */
export const TRIAL_EARLY_UNTIL = Date.UTC(2026, 8, 1); // 1 сентября 2026, 00:00 UTC

/** Сколько дней даётся в тестовой версии тем, кто успел. */
export const TRIAL_DAYS_EARLY = 30;

/** Сколько дней даётся после границы. */
export const TRIAL_DAYS_REGULAR = 14;

/**
 * Длительность пробного периода для подключения в момент `connectedAt`.
 *
 * `connectedAt` — миллисекунды эпохи. Ровно граница (`TRIAL_EARLY_UNTIL`)
 * относится уже к обычному сроку: «до 01.09.2026» читается как «включительно
 * по 31 августа», и трактовать иначе значит спорить с человеком о сутках.
 */
export function trialDaysFor(connectedAt: number): number {
  return connectedAt < TRIAL_EARLY_UNTIL ? TRIAL_DAYS_EARLY : TRIAL_DAYS_REGULAR;
}

/** Когда закончится пробный период, начатый в `connectedAt`. */
export function trialEndsAt(connectedAt: number): number {
  return connectedAt + trialDaysFor(connectedAt) * 86_400_000;
}
