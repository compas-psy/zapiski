/**
 * Включена ли синхронизация с Облаком Записок (CMPAS Cloud).
 *
 * ── Почему выключено ─────────────────────────────────────────────────────
 *
 * SEC-001 (`docs/dev/security/AUDIT.md`,
 * `docs/dev/security/SEC-001-zero-knowledge-design.md`): сегодня
 * `ZapiskiCloudBackend` не оборачивает содержимое заметки собственным
 * ключом синхронизации вовсе — сервер получает то же самое, что лежит на
 * диске (за вычетом заметок, которые человек сам зашифровал паролем через
 * `crypto/notes.ts`, — тех меньшинство). Показывать «Облако Записок» как
 * рабочий вариант хранения, пока это так, значит вести людей на известный,
 * задокументированный дефект.
 *
 * ── Почему выключатель, а не удаление кода ───────────────────────────────
 *
 * `ZapiskiCloudBackend` (`sync/zapiski-cloud.ts`), весь `sync/**`,
 * серверные маршруты `/api/v1/vault/*` — написаны, покрыты тестами и
 * станут точкой, на которую ляжет шифрование границы (SEC-001 design §1),
 * а не будут переписаны заново. Удалить их сейчас значило бы через
 * несколько недель писать их снова.
 *
 * ── Что выключатель обязан делать, а не только «спрятать кнопку» ────────
 *
 * Это не пункт в настройках сам по себе. У кого Облако УЖЕ было подключено
 * — при следующем старте приложение обязано отказаться его переподключать
 * (`AppController.resumeCloud`, `connectCloud`), а не продолжать молча
 * слать содержимое заметок в открытом виде только потому, что человек
 * когда-то согласился, ещё не зная про SEC-001. `ZapiskiCloudBackend`
 * дополнительно отказывается конструироваться вовсе, пока флаг выключен, —
 * так безопасность synка не зависит от того, что каждый вызывающий код не
 * забыл собственную проверку. Экран настроек обязан сказать честно —
 * «облачная синхронизация временно недоступна», а не просто убрать
 * карточку и оставить человека гадать, куда делись заметки.
 *
 * ── Это НЕ решение SEC-001 ────────────────────────────────────────────────
 *
 * Когда переключатель снова станет `true`, включать его обязана
 * реализация zero-knowledge-синка (SEC-001 design doc, «фаза 1»), а не тот
 * же дефект под той же кнопкой.
 */
export const CLOUD_SYNC_ENABLED = false;
