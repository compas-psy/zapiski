/**
 * Включена ли синхронизация с Облаком Записок (CMPAS Cloud).
 *
 * ── Почему выключатель был выключен и почему включён теперь ──────────────
 *
 * Выключили его по SEC-001 (`docs/dev/security/AUDIT.md`): облако не
 * оборачивало содержимое заметки собственным ключом синхронизации — сервер
 * получал то же самое, что лежит на диске. Показывать «Облако Записок» как
 * рабочий вариант хранения, пока это так, значило вести людей на известный,
 * задокументированный дефект.
 *
 * Включён он обратно не потому, что «прошло время», а потому, что дефекта
 * больше нет: содержимое, CRDT-обновления и версии уходят конвертом
 * AES-256-GCM под ключами, выведенными из SMK, которого сервер не знает
 * (`crypto/sync-keys.ts`, `sync/sync-crypto.ts`), путь заменён токеном
 * `HMAC(K_manifest, путь)`, а прикладная фабрика физически не умеет собрать
 * бэкенд без ключа (`packages/app/src/state/cloud-access.ts`). Сквозной
 * сценарий двух устройств проверяется целиком —
 * `packages/core/test/sec001.e2e.test.ts`, — а не по частям.
 *
 * ── Этот флаг — НЕ единственное условие ──────────────────────────────────
 *
 * Второе условие платформенное и живёт рядом:
 * `platformSupportsSecureKeyStorage`. Ключ синка обязан лежать в хранилище
 * уровня Keychain/Keystore/DPAPI; у браузера аппаратного эквивалента нет, а
 * `IndexedDB` читается любым JS того же origin (design §3.1). Поэтому в вебе
 * Облако остаётся выключенным честно, отдельной причиной, а не этим флагом,
 * и локальные ЗАПИСКИ там работают как работали.
 *
 * ── Что выключатель обязан делать, если его снова выключат ───────────────
 *
 * Это не пункт в настройках сам по себе: у кого Облако уже подключено,
 * приложение обязано отказаться его переподключать (`AppController.
 * resumeCloud`, `connectCloud`), а `ZapiskiCloudBackend` — отказаться
 * конструироваться вовсе, чтобы безопасность синка не зависела от того, что
 * каждый вызывающий код не забыл собственную проверку.
 */
export const CLOUD_SYNC_ENABLED = true;
