/**
 * Какие места хранения предлагаются человеку на выбор.
 *
 * ── Решение заказчика ───────────────────────────────────────────────────────
 *
 * «Пока в настройках скрой Яндекс.Диск и WebDav — они по сути конкуренты
 * облаку, за которое мы просим оплату».
 *
 * ── Почему выключатель, а не удаление ───────────────────────────────────────
 *
 * Оба backend'а написаны, покрыты тестами и работают: `sync/yandex.ts`,
 * `sync/webdav.ts`, их разбор PROPFIND, ETag'и и разрешение конфликтов. Слово
 * «пока» в решении означает, что они вернутся, — а выбросить и написать заново
 * стоило бы дороже, чем строчка `false`.
 *
 * ── Что выключатель НЕ делает ───────────────────────────────────────────────
 *
 * Он прячет ВЫБОР, а не отбирает уже сделанный. У кого хранилище уже стоит на
 * Яндекс.Диске или WebDAV, карточка остаётся видимой: иначе человек не смог бы
 * ни посмотреть, где лежат его заметки, ни уйти оттуда — а это ровно то
 * «приложение само сменило место хранения», из-за которого мы однажды уже
 * получили утро с пустым списком.
 */
export const OWN_STORAGE_ENABLED = false;
