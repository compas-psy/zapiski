/**
 * Какие места хранения предлагаются человеку на выбор.
 *
 * ── Решение заказчика ───────────────────────────────────────────────────────
 *
 * «Пока в настройках скрой Яндекс.Диск и WebDav — они по сути конкуренты
 * облаку, за которое мы просим оплату».
 *
 * ── Почему выключатель, а не удаление ───────────────────────────────────────
 *
 * Оба backend'а написаны, покрыты тестами и работают: `sync/yandex.ts`,
 * `sync/webdav.ts`, их разбор PROPFIND, ETag'и и разрешение конфликтов. Слово
 * «пока» в решении означает, что они вернутся, — а выбросить и написать заново
 * стоило бы дороже, чем строчка `false`.
 *
 * ── Что выключатель НЕ делает ───────────────────────────────────────────────
 *
 * Он прячет ВЫБОР, а не отбирает уже сделанный. У кого хранилище уже стоит на
 * Яндекс.Диске или WebDAV, карточка остаётся видимой: иначе человек не смог бы
 * ни посмотреть, где лежат его заметки, ни уйти оттуда — а это ровно то
 * «приложение само сменило место хранения», из-за которого мы однажды уже
 * получили утро с пустым списком.
 */
export const OWN_STORAGE_ENABLED = false;

/**
 * Предлагается ли «Копия в другой папке» — вторая папка на этом же устройстве
 * (флешка, папка клиента Яндекс.Диска или другого облака).
 *
 * ── Решение заказчика ───────────────────────────────────────────────────────
 *
 * «Из хранилища и синхронизации убери „Копия в другой папке“ (то, что касается
 * Яндекс.Диска)».
 *
 * ── Почему это тот же случай, что выше ──────────────────────────────────────
 *
 * Способ работает: `LocalFolderBackend` написан и покрыт тестами, папку
 * выбирает `pickVaultDirectory`. Убирается не умение, а ПРЕДЛОЖЕНИЕ — по той
 * же причине, что Яндекс.Диск и WebDAV: папка чужого облачного клиента
 * заменяет собой наше облако, и держать её в списке наравне значит предлагать
 * человеку обойти то, ради чего продукт существует.
 *
 * ── Что выключатель НЕ делает ───────────────────────────────────────────────
 *
 * Он прячет ВЫБОР, а не отбирает сделанный: у кого заметки лежат в такой папке
 * сейчас, карточка остаётся видимой. Иначе человек не увидел бы, где его
 * заметки, и не смог бы оттуда уйти — то самое «приложение само сменило место
 * хранения», которое мы уже проходили.
 */
export const FOLDER_COPY_ENABLED = false;
