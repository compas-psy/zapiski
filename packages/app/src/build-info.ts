/**
 * Отпечаток сборки: по нему видно, ЧТО именно установлено.
 *
 * ── Зачем ────────────────────────────────────────────────────────────────
 *
 * Номер версии в `tauri.conf.json` прибит гвоздями (`0.1.0`) и не менялся ни
 * разу. Экран «О приложении» его честно показывает — и потому не отвечает на
 * единственный вопрос, который к нему приходят задать: «у меня свежая сборка
 * или вчерашняя?». Из-за этого нельзя ни проверить, доехала ли починка, ни
 * понять, что лежит по ссылке на установщик.
 *
 * Отпечаток решает это, не требуя дисциплины: он берётся из коммита, а
 * коммит меняется сам. Ручное поднятие версии осталось бы обязанностью,
 * которую однажды забывают, — и мы это уже наблюдали.
 *
 * Значение приходит через `VITE_BUILD_ID`, потому что Vite подставляет
 * переменные с префиксом `VITE_` сам: ни один из трёх конфигов сборки трогать
 * не пришлось. Локально его нет — тогда честное `dev`, а не выдуманный номер.
 */
/* `import.meta.env` не описан в типах этого пакета: он не зависит от Vite и
   собирается в том числе для тестов на Node. Поэтому доступ через приведение,
   а не через `vite/client` в tsconfig — тянуть типы сборщика в ядро
   приложения ради одной строки было бы дороже. */
const META = import.meta as unknown as { env?: Record<string, unknown> };
const RAW: unknown = META.env?.['VITE_BUILD_ID'];

export const BUILD_ID: string = typeof RAW === 'string' && RAW.trim() !== '' ? RAW.trim() : 'dev';
