/**
 * Доступно ли Облако Записок на этом устройстве.
 *
 * ── Что здесь было и почему этого больше нет ─────────────────────────────
 *
 * Модуль держал инвариант «бэкенд Облака НЕ СУЩЕСТВУЕТ без ключа сквозного
 * шифрования»: состояние `CloudAccess`, онбординг ключа, код восстановления,
 * платформенный замок. Решением владельца сквозное шифрование вырезано из
 * MVP целиком — не отложено, а убрано со всех экранов, — и вернётся отдельной
 * продуктовой функцией на биометрии или внешней ключнице.
 *
 * Вместе с ним ушёл и весь этот аппарат. Он не просто стал не нужен: в
 * прошлый раз он оставил человека в тупике («ключ есть у аккаунта, а здесь
 * его нет» — и ни одной кнопки), и это была не случайность реализации, а
 * прямое следствие модели, где облако без ключа не собирается.
 *
 * ── Чем шифрование заменено, чтобы это было сказано вслух ────────────────
 *
 * Содержимое шифруется НА СЕРВЕРЕ, ключом сервера (`services/blobStore.ts`).
 * Это защита от чтения файлов в обход работающего приложения — снимок диска,
 * резервная копия, увезённый том. Сервер содержимое прочитать может, и
 * интерфейс обязан говорить именно так, а не обещать обратного.
 *
 * Заметки одного человека от другого отделяет серверная авторизация — она
 * покрыта сторожами IDOR по всем методам (`server/test/security.perimeter`).
 */
import { CLOUD_SYNC_ENABLED, type PlatformCapabilities } from '@zapiski/core';

/**
 * Одно условие вместо прежних двух.
 *
 * Платформенный замок снят намеренно: он требовал хранилища уровня
 * Keychain/Keystore/DPAPI под ключ шифрования, а ключа больше нет. Пока он
 * стоял, облака не было ни в браузере, ни на телефоне без биометрии — то
 * есть у части людей его не было вовсе, и узнавали они об этом, только
 * добравшись до настроек.
 *
 * Аргумент платформы вернётся вместе с продуктовым шифрованием — тогда ему
 * снова будет что охранять.
 */
export function cloudAvailable(_platform: PlatformCapabilities): boolean {
  return CLOUD_SYNC_ENABLED;
}
