/**
 * Контракт приложения ЗАПИСКИ.
 *
 * `packages/app` содержит ВСЕ экраны и ВСЁ поведение. Платформенные оболочки
 * (`apps/web`, `apps/desktop`, `apps/mobile`) обязаны быть тонкими: они только
 * создают `AppHost` и монтируют `<App host={...} />`.
 *
 * Если оболочке понадобилось отрисовать что-то своё — это ошибка проектирования
 * (docs/ARCHITECTURE.md §1): значит, у `AppHost` не хватает порта, и добавлять
 * нужно порт, а не экран.
 */

import type {
  PdfRenderer,
  PlatformCapabilities,
  VaultOwner,
  VaultPath,
  VaultStorage,
  SyncBackend,
} from '@zapiski/core/contract';
import type { FeedbackContext, FeedbackEntry } from '@zapiski/core';

/** Всё, что приложение получает от платформы. Больше ему ничего не нужно. */
export interface AppHost {
  readonly platform: PlatformCapabilities;

  /**
   * Хранилище последнего открытого vault'а, если оно уже известно
   * (например, восстановлено из permission handle в вебе). `null` — покажем
   * онбординг с выбором места хранения (SCREENS §1, шаг 2).
   *
   * `owner` — чьё хранилище открыть. Оболочка помнит выбор для каждого
   * владельца отдельно; `null` для незнакомого владельца означает «места ещё
   * нет», а не «папка пропала».
   */
  restoreVault(owner?: VaultOwner): Promise<VaultStorage | null>;

  /** Настройки приложения вне vault'а: тема, акцент, язык, выбранный backend. */
  readonly prefs: PreferencesStore;

  /** Открыть ссылку во внешнем браузере. */
  openExternal(url: string): Promise<void>;

  /**
   * Открыть вложение системным приложением (замечание 16).
   *
   * Порт необязателен: в вебе настоящего пути к файлу нет, там открытие идёт
   * через `blob:`-адрес и `openExternal`. А в оболочках наоборот — `blob:`
   * системе бесполезен: Android и Windows ждут либо реальный путь, либо
   * `content://`. Из-за этого «по клику открыть файл» работало ровно на одной
   * платформе из трёх.
   *
   * Возвращает `false`, если открыть не удалось: приложение тогда пробует
   * прежний путь через `blob:`, а не оставляет человека без результата.
   */
  openAttachment?(path: VaultPath): Promise<boolean>;

  /**
   * Системное «назад»: кнопка и жест Android.
   *
   * Оболочка сообщает о нажатии и получает ответ: `true` — приложение шаг
   * назад сделало само, `false` — идти назад некуда, и система вправе увести
   * человека из приложения.
   *
   * Порт необязателен: у веба своё «назад» — браузерное, у настольного окна
   * такой кнопки нет вовсе. Куда именно возвращаться, оболочка не решает: это
   * вопрос про экраны, а не про платформу (ARCHITECTURE §1).
   *
   * Возвращает функцию отписки.
   */
  onSystemBack?(handler: () => boolean): () => void;

  /**
   * Базовый URL API облака, **включая префикс версии**: `…/api/v1`.
   *
   * Приложение дописывает к нему только путь ручки (`/auth/magic-link`),
   * поэтому база без префикса даёт 404. Формулировка уточнена после того,
   * как веб отдавал `origin + /api/v1`, а обе Tauri-оболочки — голый origin,
   * и вход на Windows и Android молча ломался.
   */
  readonly cloudBaseUrl: string;
}

export interface PreferencesStore {
  get<T>(key: string, fallback: T): Promise<T>;
  set<T>(key: string, value: T): Promise<void>;
  /** Реактивная подписка — смена темы применяется мгновенно, без перезагрузки. */
  subscribe(key: string, handler: (value: unknown) => void): () => void;
}

