#!/usr/bin/env node
/**
 * Каждое действие с окном названо в правах — иначе оно молча не сработает.
 *
 * ── Что случилось ───────────────────────────────────────────────────────────
 *
 * Заказчик: «Windows — окно не сворачивается». Кнопка на месте, обработчик на
 * месте, `win.minimize()` вызывается. Отказывает не наш код, а Tauri: в
 * версии 2 каждая команда ядра проходит проверку прав из
 * `src-tauri/capabilities/*.json`, и набор `core:default` даёт по окну только
 * ЧТЕНИЕ — `is-maximized`, `is-minimized`, размеры, монитор. Свернуть,
 * закрыть, развернуть и потащить окно за нашу строку заголовка он не
 * разрешает. Отклонённый вызов не бросает ничего заметного: промис отвергнут,
 * `void` его проглатывает, на экране — ничего.
 *
 * Список умолчания взят не из памяти, а из самого пакета:
 * `tauri-2.x/permissions/window/autogenerated/reference.md`, раздел
 * «Default Permission». Там 30 разрешений, и ни одного изменяющего, кроме
 * `internal-toggle-maximize` (двойной клик по полосе перетаскивания).
 *
 * Окно у нас безрамочное (`decorations: false`), системных кнопок нет —
 * значит, без этих прав окно нельзя ни свернуть, ни закрыть, ни сдвинуть.
 *
 * ── Что проверяет этот сторож ───────────────────────────────────────────────
 *
 * Правило простое и не требует копии чужих умолчаний: **каждое действие с
 * окном, которое есть в коде, обязано быть названо в правах поимённо**. Так
 * же читается и описание самого файла прав: «каждое право соответствует
 * реальному вызову». Лишняя строка про `is-maximized` дешевле, чем догадка о
 * том, что входит в чужой набор по умолчанию и не изменится в следующей
 * версии.
 *
 * Отдельно — перетаскивание: его не видно в вызовах, оно приходит из атрибута
 * `data-tauri-drag-region` в разметке. Права ему нужны те же.
 */
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DESKTOP_SRC = join(ROOT, 'apps/desktop/src');
const CAPABILITY = join(ROOT, 'apps/desktop/src-tauri/capabilities/default.json');
/** Разметка общая для трёх оболочек: полоса перетаскивания живёт здесь. */
const APP_SRC = join(ROOT, 'packages/app/src');

/** Файл, где заведён порт управления окном. Вызовы ищем по имени переменной. */
const WINDOW_PORT = join(DESKTOP_SRC, 'platform/window.ts');

function files(dir, extensions) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) out.push(...files(path, extensions));
    else if (extensions.some((extension) => entry.endsWith(extension))) out.push(path);
  }
  return out;
}

/** `toggleMaximize` → `toggle-maximize`: так права и называются. */
function kebab(name) {
  return name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

const problems = [];

const port = readFileSync(WINDOW_PORT, 'utf8');
/* `getCurrentWindow()` кладётся в переменную, дальше всё идёт через неё. */
const holder = /const\s+(\w+)\s*=\s*getCurrentWindow\(\)/.exec(port)?.[1];
if (holder === undefined) {
  problems.push(`в ${WINDOW_PORT} не найден вызов getCurrentWindow() — сторож ослеп`);
}

const used = new Set();
if (holder !== undefined) {
  for (const match of port.matchAll(new RegExp(`\\b${holder}\\s*\\.\\s*(\\w+)\\s*\\(`, 'g'))) {
    used.add(match[1]);
  }
}

/* События окна (`onResized`, `onCloseRequested`) идут через подписку, а не
   через права окна: их покрывает `core:event:default`. */
const EVENTS = new Set(['onResized', 'onMoved', 'onCloseRequested', 'onFocusChanged', 'listen', 'once']);
const required = new Set(
  [...used].filter((name) => !EVENTS.has(name)).map((name) => `core:window:allow-${kebab(name)}`),
);

/* Перетаскивание окна за свою строку заголовка. В коде вызова нет — есть
   атрибут в разметке, и он тоже упирается в права. */
const draggable = files(APP_SRC, ['.tsx', '.ts']).some((path) =>
  readFileSync(path, 'utf8').includes('data-tauri-drag-region'),
);
if (draggable) required.add('core:window:allow-start-dragging');

const capability = JSON.parse(readFileSync(CAPABILITY, 'utf8'));
const granted = new Set(capability.permissions ?? []);

for (const permission of [...required].sort()) {
  if (!granted.has(permission)) {
    problems.push(`нет права ${permission} — действие с окном молча не сработает`);
  }
}

/* И обратно: право без вызова — это либо мусор, либо забытая правка кода.
   Держим список честным в обе стороны, как обещает описание файла прав. */
for (const permission of [...granted].sort()) {
  if (permission.startsWith('core:window:allow-') && !required.has(permission)) {
    problems.push(`право ${permission} есть, а вызова нет — либо лишнее, либо код потерялся`);
  }
}

if (problems.length > 0) {
  console.log('права окна: не сходятся');
  for (const problem of problems) console.log(`  · ${problem}`);
  process.exit(1);
}

console.log(
  `права окна: сходятся — действий ${required.size}, ` +
    `перетаскивание ${draggable ? 'учтено' : 'не используется'}`,
);
