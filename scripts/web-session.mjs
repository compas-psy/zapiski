/**
 * Подставить «уже вошли» браузерным прогонам.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 *
 * В вебе аккаунт стал условием входа: без него приложение показывает экран
 * входа и дальше не пускает (заказчик — иначе заметки на разных устройствах
 * выглядят потерянными). Прогоны при этом проверяют не ворота, а продукт за
 * ними, и настоящий вход им недоступен: ни сервера, ни почты рядом нет.
 *
 * Поэтому сессия кладётся в те же настройки, из которых приложение её читает
 * на старте. Это ровно то состояние, в котором человек оказывается после
 * входа, — прогон ничего не обходит и не подменяет в самом приложении.
 *
 * Сети от этого не появляется: облако подключается только при живом входе, а
 * восстановленная сессия просто заполняет аккаунт.
 */

/** Ключ настроек веба: `NAMESPACE` из apps/web/src/prefs.ts + имя из AUTH_PREF. */
const SESSION_KEY = 'zapiski.prefs.auth.session';

export async function seedWebSession(page, email = 'progon@example.test') {
  await page.addInitScript(
    ([key, value]) => {
      try {
        window.localStorage.setItem(key, value);
      } catch {
        /* Приватный режим — прогон тогда упрётся в ворота и честно упадёт. */
      }
    },
    [
      SESSION_KEY,
      JSON.stringify({
        accessToken: 'progon-access-token',
        refreshToken: 'progon-refresh-token',
        deviceId: 'progon-device-0001',
        email,
        expiresAt: Date.now() + 3600_000,
      }),
    ],
  );
}
