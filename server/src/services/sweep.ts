/**
 * Расписание уборки: просроченные версии (ТЗ §4.2), отработавшие
 * magic-токены и повтор пересылки в ПРАКТИКУ (C4).
 *
 * Вынесено из `index.ts` отдельным модулем не ради красоты: `index.ts`
 * запускает `main()` прямо при импорте, поэтому проверить его расписание
 * тестом было нельзя вовсе. Здесь — чистая функция над колбэком, без базы и
 * без сети.
 *
 * ── Почему есть прогон на старте ────────────────────────────────────────────
 *
 * Раньше расписание состояло из одного `setInterval` на час, и первая уборка
 * случалась не раньше чем через час после подъёма контейнера. Каждая выкладка
 * пересоздаёт контейнер и обнуляет отсчёт — в день с выкладками чаще раза в
 * час уборка не проходила НИ РАЗУ, и события, не дошедшие до ПРАКТИКИ с
 * первой попытки (или вообще миновавшие строчный путь — как вставленные
 * миграцией `0012_analytics_consent_backfill.sql`), оставались
 * непересланными навсегда. Молча: в логе это выглядит как «мост включён,
 * переслано 0».
 *
 * Прогон отложен на `SWEEP_FIRST_RUN_MS`, а не сделан немедленно: подъём
 * сервера не должен ждать обход базы. Тридцати секунд хватает, чтобы
 * контейнер успел принять трафик, и это на два порядка меньше часа — то
 * есть переживает любой разумный темп выкладок.
 */

export const SWEEP_INTERVAL_MS = 60 * 60 * 1000;
export const SWEEP_FIRST_RUN_MS = 30 * 1000;

/**
 * Заводит расписание и возвращает функцию остановки.
 *
 * `runOnce` вызывается уже с проглоченной ошибкой: отказ одной уборки не
 * снимает расписание — иначе одна недоступность базы выключала бы пересылку
 * до следующего перезапуска. Логированием отказа занимается сам `runOnce`.
 */
export function startSweeper(
  runOnce: () => Promise<void>,
  intervalMs: number = SWEEP_INTERVAL_MS,
  firstRunMs: number = SWEEP_FIRST_RUN_MS,
): () => void {
  const safely = (): void => {
    void runOnce().catch(() => undefined);
  };

  const first = setTimeout(safely, firstRunMs);
  const repeat = setInterval(safely, intervalMs);
  first.unref?.();
  repeat.unref?.();

  return () => {
    clearTimeout(first);
    clearInterval(repeat);
  };
}
