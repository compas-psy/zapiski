-- Обращения из беты.
--
-- ── Почему идентификатор придумывает клиент ─────────────────────────────────
--
-- Форма работает офлайн: обращение ложится в очередь на устройстве и уходит,
-- когда появится сеть. Досылка повторяется — сеть моргнула на середине ответа,
-- приложение свернули, телефон уснул. Без идемпотентности одно нажатие
-- превращалось бы в три строки, а разбирающий считал бы их тремя разными
-- людьми: приоритет темы измеряется числом ЛЮДЕЙ, и дубли ломают именно его.
--
-- Поэтому первичный ключ приходит с устройства, а вставка идёт
-- `ON CONFLICT DO NOTHING`. Подделать чужой ключ ничего не даёт: обращения не
-- читаются наружу и не связаны с аккаунтом.
--
-- ── Почему нет ссылки на пользователя ───────────────────────────────────────
--
-- Аккаунта может не быть вовсе (ТЗ §4.1: приложение локальное). Связь с
-- пользователем здесь не только не нужна — она вредна: единственный способ
-- ответить человеку это контакт, который он оставил САМ и осознанно.
--
-- ── Чего здесь нет и не будет ───────────────────────────────────────────────
--
-- Ни путей к файлам, ни заголовков, ни размеров хранилища в штуках. Диагностика
-- приходит уже в корзинах и кодах: собирает её клиент
-- (`packages/core/src/feedback/report.ts`), а сторож утечки стоит там же.
CREATE TABLE IF NOT EXISTS feedback (
  -- Ключ с устройства: UUID, придуманный клиентом.
  id            uuid        PRIMARY KEY,
  -- Момент, когда человек нажал «Отправить». Может быть заметно раньше
  -- получения: обращение могло пролежать в очереди сутки без сети.
  created_at    timestamptz NOT NULL,
  received_at   timestamptz NOT NULL DEFAULT now(),
  kind          text        NOT NULL
                            CHECK (kind IN ('broken', 'awkward', 'want-feature', 'other')),
  -- Сообщение человека в поддержку. Единственное место продукта, где мы
  -- принимаем свободный текст, и он идёт в поддержку, а не в аналитику.
  --
  -- Колонка называется `message`, а не `body`, намеренно: `body` — словарь
  -- содержимого ЗАМЕТКИ, и сторож схемы (`schema.zero-knowledge.test.ts`)
  -- запрещает его во всей базе. Запрет правильный, а имя было неточным:
  -- здесь лежит не заметка, а письмо, которое человек написал нам сам.
  message       text        NOT NULL,
  -- Контакт, оставленный ДОБРОВОЛЬНО. NULL — человек ответа не просил.
  contact       text,
  entry         text        NOT NULL
                            CHECK (entry IN ('menu', 'error', 'sync_conflict', 'slow_op')),
  -- Обстоятельства и диагностика — как прислал клиент, уже в корзинах и кодах.
  context       jsonb,
  diagnostics   jsonb,
  -- Снимок экрана прикладывается только явным действием и после
  -- предупреждения. В базе лежит АДРЕС в томе, а не байты: инвариант
  -- zero-knowledge оставляет в БД единственную бинарную колонку — шифротекст
  -- CRDT (ТЗ §2.1.5). NULL — снимка нет.
  screenshot_key text,
  -- Судьба обращения: new → triaged → answered → resolved.
  status        text        NOT NULL DEFAULT 'new'
                            CHECK (status IN ('new', 'triaged', 'answered', 'resolved')),
  answered_at   timestamptz,
  resolved_at   timestamptz,
  updated_at    timestamptz NOT NULL DEFAULT now()
);

-- Ночной цикл забирает новые по `received_at`, а не по `created_at`: обращение
-- из очереди приходит с вчерашней датой создания и иначе не попало бы в выборку
-- «с прошлого раза» никогда.
CREATE INDEX IF NOT EXISTS feedback_received_idx ON feedback (received_at);
CREATE INDEX IF NOT EXISTS feedback_status_idx ON feedback (status, received_at);

COMMENT ON COLUMN feedback.id IS
  'UUID с устройства: идемпотентность досылки из офлайн-очереди.';
COMMENT ON COLUMN feedback.message IS
  'Сообщение человека в поддержку. В аналитику не попадает ни в каком виде (только корзина s/m/l).';
COMMENT ON COLUMN feedback.contact IS
  'Контакт для ответа, оставленный добровольно. NULL — ответа не просили.';
