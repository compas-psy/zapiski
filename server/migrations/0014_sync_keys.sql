-- 0014_sync_keys — обёрнутый ключ синхронизации аккаунта (SEC-001, фаза 1).
--
-- ── Что здесь лежит и почему это безопасно ───────────────────────────────
--
-- SMK (sync master key) — 256-битный случайный ключ, из которого клиент
-- выводит доменные подключи для содержимого, CRDT и версий
-- (`packages/core/src/crypto/sync-keys.ts`). Сам SMK на сервер НЕ ПОПАДАЕТ
-- никогда. Сюда кладётся только `wrapped_smk` — тот же SMK, зашифрованный
-- AES-256-GCM ключом, выведенным из кода восстановления, который знает
-- ТОЛЬКО человек.
--
-- Сервер, включая сервер полностью скомпрометированный, из этой строки не
-- может получить ничего: у него нет кода восстановления, а перебирать
-- нечего — код это 256 бит CSPRNG, а не пароль (design §6.0 и уточнение
-- заказчика «не менее 256 бит»). Именно поэтому здесь нет и не нужно
-- параметров Argon2id: замедлять перебор равномерно случайного
-- 256-битного секрета незачем.
--
-- `account_salt` — публичный параметр HKDF, а не секрет. Он обязан быть
-- одинаковым на всех устройствах аккаунта: иначе один и тот же SMK дал бы
-- на разных устройствах РАЗНЫЕ доменные ключи и синк развалился бы
-- (design §2.2). Публичность соли — штатное свойство HKDF, тот же класс
-- данных, что и соль vault'а в `.zapiski/meta/crypto.json`.
--
-- `check_blob` — короткий проверочный конверт, зашифрованный тем же
-- доменным ключом манифеста. Он позволяет клиенту убедиться, что код
-- восстановления верный, НЕ расшифровывая настоящие заметки — тот же
-- приём, что уже применён к паролю vault'а (`openCheck`, `store.ts`).
--
-- Одна строка на АККАУНТ, не на устройство и не на заметку: у всех
-- устройств аккаунта один и тот же SMK (design §4, §5) — асимметричного
-- обмена ключами между устройствами конструкция не требует.

CREATE TABLE sync_keys (
  user_id      uuid PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  -- SMK под ключом из кода восстановления. Для сервера — непрозрачные байты.
  wrapped_smk  bytea       NOT NULL,
  -- Публичная соль HKDF аккаунта. Общая у всех устройств, секретом не является.
  account_salt bytea       NOT NULL,
  -- Проверочный конверт: даёт проверить код, не трогая настоящие заметки.
  check_blob   bytea       NOT NULL,
  -- Версия схемы ключей на клиенте. Позволяет менять раскладку доменных
  -- строк, не гадая, чем зашифрован уже лежащий в облаке объект.
  key_version  integer     NOT NULL DEFAULT 1,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE sync_keys IS
  'SEC-001: обёрнутый ключ синхронизации аккаунта. Сервер не может его развернуть — код восстановления известен только человеку.';
COMMENT ON COLUMN sync_keys.wrapped_smk IS
  'AES-256-GCM(SMK) под ключом из кода восстановления. Непрозрачные байты.';
COMMENT ON COLUMN sync_keys.account_salt IS
  'Публичная соль HKDF. Обязана быть одинаковой на всех устройствах аккаунта.';
COMMENT ON COLUMN sync_keys.check_blob IS
  'Проверочный конверт для проверки кода восстановления без расшифровки заметок.';
