-- 0009_analytics_event_id — идемпотентность приёма аналитики (Д-6, C3).
--
-- Повтор — штатный сценарий для офлайн-очереди ЗАПИСОК, а не редкость:
-- сервер мог записать батч и ответить, ответ потерялся по дороге, клиент не
-- получил `ok`, `ack` не выполнен, и при следующем выходе в сеть та же
-- пачка уходит снова. Без ключа события единственный способ отличить
-- «уже было» от «новое» — сравнить содержимое, а содержимое умышленно не
-- хранит ничего, что позволило бы это сделать надёжно (правило 2,
-- charter/12_ANALYTICS.md §1). Итог без этой миграции: счётчики на панели
-- завышаются на каждый ретрай.
--
-- `event_id` генерируется НА УСТРОЙСТВЕ в момент постановки события в
-- очередь (buildAnalyticsEvent, packages/core/src/analytics/schema.ts), а
-- не при отправке — иначе повторная попытка отправить ту же пачку породила
-- бы НОВЫЙ id и не защитила бы ничего. Здесь — только приём: уникальный
-- индекс делает `ON CONFLICT (event_id) DO NOTHING` в маршруте бесплатным
-- дублем вместо задвоенной строки.
--
-- Колонка добавляется с DEFAULT, чтобы существующие строки (если они
-- есть — Д-4 объясняет, почему на практике их, скорее всего, нет: приёмник
-- отвергал каждый батч до соответствующей правки) получили значение без
-- отдельного бэкофилла, а затем DEFAULT снимается: новые события обязаны
-- приносить id с устройства, а не получать его молча на сервере — id,
-- рождённый на сервере, не был бы ключом идемпотентности ни для чего.
ALTER TABLE analytics_events ADD COLUMN IF NOT EXISTS event_id uuid NOT NULL DEFAULT gen_random_uuid();
ALTER TABLE analytics_events ALTER COLUMN event_id DROP DEFAULT;

CREATE UNIQUE INDEX IF NOT EXISTS analytics_events_event_id_idx ON analytics_events (event_id);
