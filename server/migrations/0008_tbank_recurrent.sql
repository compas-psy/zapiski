-- 0008_tbank_recurrent — постоянный ключ плательщика для рекуррентного платежа.
--
-- Т-Касса присылает `RebillId` — идентификатор, по которому карту можно
-- списать снова, — ТОЛЬКО если `Init` ушёл с `Recurrent: 'Y'` и `CustomerKey`.
-- Без них поле под `RebillId` в схеме есть, а самого значения не бывает
-- никогда: подписка не продлевается, и понять это можно лишь через месяц
-- после первой оплаты.
--
-- Ключ плательщика — СВОЙ, непрозрачный, а не наш идентификатор пользователя:
-- своих идентификаторов на чужую сторону не отправляем. Он должен пережить и
-- смену секретов, и пересоздание сессий, поэтому хранится, а не выводится.
ALTER TABLE payment_orders ADD COLUMN IF NOT EXISTS customer_key text;
