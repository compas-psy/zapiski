-- Согласия пользователя (152-ФЗ и «О рекламе»).
--
-- Заказчик: «Мне нужно собирать согласия на рекламу (отдельное согласие,
-- непреднажатое и необязательное) и обработку ПДн (пользовательское
-- соглашение)».
--
-- ── Почему это отдельные столбцы, а не один флаг ────────────────────────────
--
-- Согласие на обработку персональных данных и согласие на рекламные рассылки —
-- РАЗНЫЕ согласия и по закону, и по смыслу. Первое обязательно: без него
-- аккаунта нет вовсе. Второе добровольно, даётся отдельным действием и в любой
-- момент отзывается. Складывать их в один флаг значило бы получать рекламное
-- согласие «в нагрузку», а это ровно то, что запрещено.
--
-- ── Почему хранится ВЕРСИЯ и МОМЕНТ ─────────────────────────────────────────
--
-- Согласие — юридический факт: важно не только «да», а какую именно редакцию
-- документа человек принял и когда. Редакция меняется — прежнее согласие не
-- становится согласием на новый текст. Без этих двух полей доказать согласие
-- нечем, а отозванное согласие не отличить от неданного.
ALTER TABLE users
  -- Обязательное: пользовательское соглашение и политика обработки ПДн.
  ADD COLUMN terms_version      text,
  ADD COLUMN terms_accepted_at  timestamptz,
  -- Добровольное: письма об обновлениях и предложениях.
  ADD COLUMN marketing_opt_in   boolean     NOT NULL DEFAULT false,
  ADD COLUMN marketing_version  text,
  ADD COLUMN marketing_at       timestamptz;

-- Аккаунты, заведённые до этой миграции, согласия не давали: у них NULL, и
-- приложение попросит принять соглашение при следующем входе. Проставлять им
-- согласие задним числом нельзя — это была бы подделка юридического факта.
COMMENT ON COLUMN users.terms_accepted_at IS
  'Момент принятия пользовательского соглашения. NULL — не принимал: согласие спрашивается при входе.';
COMMENT ON COLUMN users.marketing_opt_in IS
  'Добровольное согласие на рекламные письма. Отзывается в настройках в любой момент.';

-- Согласия даются в момент ЗАПРОСА ссылки, а аккаунт заводится в момент
-- перехода по ней. Между этими двумя моментами согласию негде жить, кроме как
-- рядом с самим токеном: записать его сразу в `users` нельзя — пользователя
-- ещё нет.
ALTER TABLE magic_tokens
  ADD COLUMN terms_version    text,
  ADD COLUMN marketing_opt_in boolean;
