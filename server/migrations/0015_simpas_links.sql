-- 0015_simpas_links — связь аккаунта ЗАПИСОК с личностью единого входа СИМПАС.
--
-- ── Принцип аддитивности ─────────────────────────────────────────────────
--
-- Миграция только ДОБАВЛЯЕТ таблицу. Ни одной существующей строки не трогает,
-- ни одной колонки не меняет, ничего не удаляет. `users.yandex_id` остаётся на
-- месте и продолжает работать: единый вход подключается рядом, а не вместо.
-- Живой человек не должен заметить, что мы что-то меняли.
--
-- ── Почему PRIMARY KEY по user_id, а не отдельный id ─────────────────────
--
-- Связь строго один-к-одному в обе стороны: у аккаунта продукта ровно одна
-- личность СИМПАС (`user_id` — первичный ключ), и одна личность СИМПАС не
-- может оказаться привязана к двум аккаунтам (`simpas_sub UNIQUE`). Оба
-- ограничения нужны: без первого один человек завёл бы себе две связи, без
-- второго чужой `sub` встал бы поверх существующего аккаунта.
--
-- ── Расхождение с присланным рецептом, намеренное ────────────────────────
--
-- В файле `docs/deploy/zapiski-0015_simpas_links.sql` репозитория `auth` ниже
-- стоял ещё и `CREATE INDEX simpas_links_sub_idx ON simpas_links (simpas_sub)`.
-- Он здесь опущен: `UNIQUE` в Postgres реализуется индексом, и второй индекс по
-- той же колонке — это лишнее место и лишняя работа при каждой записи, а
-- планировщик всё равно возьмёт уникальный. Поиск «кто это по sub», ради
-- которого индекс предлагался, обслуживается уникальным ограничением.

CREATE TABLE simpas_links (
  -- Один человек продукта — одна личность СИМПАС.
  user_id    uuid PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  -- `sub` из id_token: устойчив, не меняется и не переиспользуется.
  simpas_sub text NOT NULL UNIQUE,
  linked_at  timestamptz NOT NULL DEFAULT now()
);
