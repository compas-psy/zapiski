-- Одноразовый nonce для колбэка входа (закрытие уязвимости захвата сессии
-- через zapiski://).
--
-- ── Проблема ─────────────────────────────────────────────────────────────
--
-- `device_id` в `magic_tokens` (0001) и в `state` OAuth (routes/auth.ts)
-- защищает только ОБМЕН токена/кода на сервере — то, что ссылку из письма
-- или код Яндекса разменивает то же устройство, что их запрашивало. Дальше
-- сервер собирает `zapiski://…#access_token=…&refresh_token=…` и отправляет
-- браузер по этому адресу — а деплинк ничем не защищён: любое другое
-- приложение на телефоне может прислать точно такой же `Intent` с СОБСТВЕННЫМИ
-- (но настоящими, честно выпущенными сервером) токенами. Устройство примет
-- их как «я попросил войти» и синхронизирует локальное хранилище в чужой
-- аккаунт — обмена кодом/токеном на сервере эта атака вообще не касается.
--
-- ── Решение ──────────────────────────────────────────────────────────────
--
-- Клиент перед запросом входа генерирует одноразовый nonce и держит его у
-- себя. Сервер прокидывает его без изменений через весь цикл до финального
-- деплинка; клиент принимает колбэк, только если присланный nonce совпадает
-- с тем, что он сам недавно сгенерировал и ещё не использовал. Подделать
-- значение атакующий не может: оно никогда не покидает пару
-- клиент-браузер-сервер этого конкретного входа.
--
-- Для Яндекс-OAuth носителем уже служит подписанный `state` (JWT, отдельной
-- колонки не нужно — nonce просто становится ещё одним полем в claims).
-- Для входа по почте такого сквозного носителя не было: запрос ссылки и её
-- переход — два разных HTTP-запроса, и между ними nonce жить негде, кроме
-- как рядом с самим токеном — тем же способом, каким уже хранятся terms/
-- marketing (0004).
ALTER TABLE magic_tokens
  ADD COLUMN nonce text;

COMMENT ON COLUMN magic_tokens.nonce IS
  'Одноразовый nonce клиента, эхом возвращаемый в deep-link при обмене — привязывает финальный колбэк к устройству, реально запросившему вход.';
