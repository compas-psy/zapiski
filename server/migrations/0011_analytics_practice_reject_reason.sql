-- 0011_analytics_practice_reject_reason — контракт контура v2 (E-Z1).
--
-- Отказ приёмника («не согласие», «неизвестный аккаунт» — что угодно, что
-- он произнёс явно, `{accepted:false, reason}` на HTTP 200) — это НЕ то же
-- самое, что «мост ещё не пытался» или «сеть подвела»: строка с явным
-- отказом ждёт не столько повторной попытки того же конверта (она снова
-- откажет по той же причине, пока причина не снята), сколько снятия причины
-- — например, `consent_updated`, доставленного позже (`routes/auth.ts`).
--
-- `practice_forwarded_at IS NULL` уже отличает «дошло» от «не дошло», но не
-- отличает «дошло и ОТКАЗАНО» от «даже не дошло, недоступность». Без этой
-- колонки оператор смотрит на растущий бэклог непереслaнных строк и не может
-- сказать глазами, вызвана ли задержка отвалившейся сетью ПРАКТИКИ (пройдёт
-- само на следующем sweep'е) или тем, что триста строк одного аккаунта ждут
-- согласия, которое кто-то забыл отправить.
--
-- NULL — либо ещё не пытались, либо последняя попытка была `error`
-- (транспорт); непустая строка — последняя попытка была `rejected`, вот
-- дословная причина приёмника. Сбрасывается в NULL при успешной пересылке
-- (`retryPracticeForwarding`, `routes/analytics.ts`, `routes/auth.ts`) —
-- колонка хранит ТЕКУЩЕЕ состояние строки, а не журнал попыток.
ALTER TABLE analytics_events
  ADD COLUMN IF NOT EXISTS practice_reject_reason text;
