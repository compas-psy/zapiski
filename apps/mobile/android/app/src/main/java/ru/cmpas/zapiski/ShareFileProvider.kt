package ru.cmpas.zapiski

import androidx.core.content.FileProvider

/**
 * FileProvider для вложений заметки — картинок, которые уезжают через
 * «Поделиться».
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ ОТ `UpdatesFileProvider`
 *
 * У них разные получатели. Тот отдаёт скачанный APK системному установщику,
 * этот — картинку чужому мессенджеру. Общая область означала бы, что каждый из
 * них видит чужое: установщик — вложения, мессенджер — файл обновления.
 * Отдельные authorities стоят десяти строк манифеста и снимают вопрос целиком.
 *
 * Область — ровно `cache/share` (`res/xml/share_file_paths.xml`). Ни хранилище
 * заметок, ни ключи биометрии сюда не попадают.
 *
 * Своё имя класса обязательно и по второй причине: шаблон Tauri уже объявляет
 * провайдер с `android:name` равным `androidx.core.content.FileProvider`, и
 * второе объявление с тем же именем роняет манифест-мержер («Element
 * provider#… duplicated»).
 *
 * Реализации не требуется: вся работа в базовом классе.
 */
class ShareFileProvider : FileProvider(R.xml.share_file_paths)
