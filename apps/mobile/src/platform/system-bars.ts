/**
 * Системные панели Android: значки часов, батареи и сигнала.
 *
 * ── Что видел заказчик ──────────────────────────────────────────────────────
 *
 * «На системной панели в Андроид, которая сверху, из-за белого фона приложения
 * сливаются системные иконки аля батарея, уровень сигнала… Нужно, не делая
 * системную панель другого цвета, проявить иконки. Соответственно, этот эффект
 * должен сохраняться на всех экранах приложения».
 *
 * По умолчанию Android рисует эти значки СВЕТЛЫМИ — расчёт на тёмное
 * приложение. На нашей «Бумаге» они исчезают.
 *
 * ── Как это чинится ─────────────────────────────────────────────────────────
 *
 * Фон панели не трогаем вовсе: система умеет рисовать значки тёмными по
 * признаку `isAppearanceLightStatusBars` — «под панелью светло». Признак
 * ставится ОКНУ, а не экрану, поэтому «на всех экранах» получается само:
 * экранам об этом знать не нужно, и ни один из них ничего для этого не делает.
 *
 * Тему выбирает `packages/ui` и объявляет её атрибутом `data-theme` на корне
 * документа — там же, где её видят стили. Оболочка читает этот атрибут и
 * следит за ним: тема меняется и руками, и вслед за системой, и оба случая
 * закрываются одним наблюдателем.
 */

import { COMMANDS, call } from './ipc';

/** Тёмные значки нужны там, где под панелью светло. */
export function needsDarkIcons(theme: string | null | undefined): boolean {
  return theme === 'paper';
}

/**
 * Отправить признак окну, если он изменился.
 *
 * Возвращает то, что теперь стоит на окне, — вызывающий держит это значение и
 * передаёт обратно. Лишний вызов ничего не сломал бы, но он идёт через JNI на
 * UI-поток, а тему приложение перечитывает на каждой перерисовке корня.
 */
export function applyBarIcons(theme: string | null | undefined, applied: boolean | null): boolean {
  const dark = needsDarkIcons(theme);
  if (dark === applied) return dark;
  void call(COMMANDS.systemBarIcons, { dark }).catch(() => undefined);
  return dark;
}

/**
 * Следить за темой и держать значки видимыми.
 *
 * Возвращает функцию отписки: в приложении наблюдатель живёт столько же,
 * сколько окно, но оставлять его неостановимым — значит завести утечку там,
 * где её никто не ждёт.
 */
export function watchSystemBars(root: Element = document.documentElement): () => void {
  let applied: boolean | null = null;
  const apply = (): void => {
    applied = applyBarIcons(root.getAttribute('data-theme'), applied);
  };

  apply();
  const observer = new MutationObserver(apply);
  observer.observe(root, { attributes: true, attributeFilter: ['data-theme'] });
  return () => observer.disconnect();
}
